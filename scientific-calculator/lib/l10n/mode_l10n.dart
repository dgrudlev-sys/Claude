import 'simple_tools_l10n.dart';

Map<String, String> toolStrings(String code) {
  return {
    ..._tools['en']!,
    if (_tools[code] != null && code != 'en') ..._tools[code]!,
    ...simpleToolStrings('en'),
    if (code != 'en') ...simpleToolStrings(code),
  };
}

